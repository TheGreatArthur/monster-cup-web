-- The site's database on Supabase (Postgres). Everything lives in the "game" schema, which the
-- Supabase Data API does not expose: only the site server reaches it, as the game_server role
-- (web/db.js, DATABASE_URL). Applied once to the Supabase project; safe to run again.
--
-- Times are kept as UTC text "YYYY-MM-DD HH:MM:SS" (game.utc_text()), the format the pages and
-- the admin tools read; "at" columns holding numbers are milliseconds.

CREATE SCHEMA IF NOT EXISTS game;
REVOKE ALL ON SCHEMA game FROM PUBLIC;

-- Now (plus a shift, e.g. interval '-1 day') as UTC text.
CREATE OR REPLACE FUNCTION game.utc_text(shift interval DEFAULT interval '0')
  RETURNS text LANGUAGE sql STABLE SET search_path = '' AS
$$ SELECT to_char((now() AT TIME ZONE 'utc') + shift, 'YYYY-MM-DD HH24:MI:SS') $$;

CREATE TABLE IF NOT EXISTS game.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text NOT NULL,
  password_hash text NOT NULL,             -- "salt:key" (scrypt), "!" for Discord accounts
  created_at text NOT NULL DEFAULT game.utc_text(),
  story_seen_at text,
  supabase_id text,                        -- Supabase Auth user (Discord login)
  discord_id text,
  display_name text,
  avatar_url text
);
CREATE UNIQUE INDEX IF NOT EXISTS users_username ON game.users (lower(username));
CREATE UNIQUE INDEX IF NOT EXISTS users_supabase ON game.users (supabase_id) WHERE supabase_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS game.sessions (
  token_hash text PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES game.users(id) ON DELETE CASCADE,
  expires_at bigint NOT NULL
);

CREATE TABLE IF NOT EXISTS game.saves (
  user_id bigint PRIMARY KEY REFERENCES game.users(id) ON DELETE CASCADE,
  data bytea NOT NULL,
  size integer NOT NULL,
  sha256 text NOT NULL,
  updated_at text NOT NULL
);

-- Anti-cheat (save-check.js): the Digimon of every uploaded save, to check the next one against.
CREATE TABLE IF NOT EXISTS game.save_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES game.users(id) ON DELETE CASCADE,
  at bigint NOT NULL,
  sha256 text NOT NULL,
  digimon text,                            -- JSON, null when the save could not be read
  problems text                            -- JSON list, null when none
);
CREATE INDEX IF NOT EXISTS save_history_user ON game.save_history (user_id, id);

-- The record (0x6C bytes) the game sends in Multi Battle for a saved Digimon (referee.js).
CREATE TABLE IF NOT EXISTS game.known_records (
  record text PRIMARY KEY,
  data bytea NOT NULL,
  at text NOT NULL DEFAULT game.utc_text()
);

-- Accounts whose save broke the rules: barred from ranked play.
CREATE TABLE IF NOT EXISTS game.save_flags (
  user_id bigint PRIMARY KEY REFERENCES game.users(id) ON DELETE CASCADE,
  at text NOT NULL DEFAULT game.utc_text(),
  problems text NOT NULL
);

-- Online battles (online.js).
CREATE TABLE IF NOT EXISTS game.online_matches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mode text NOT NULL,                      -- 'room' (friendly) or 'search' (ranked)
  host_id bigint NOT NULL REFERENCES game.users(id) ON DELETE CASCADE,
  guest_id bigint NOT NULL REFERENCES game.users(id) ON DELETE CASCADE,
  started_at text NOT NULL DEFAULT game.utc_text(),
  ended_at text,
  end_reason text,
  seed bigint,
  host_won integer,
  guest_won integer,
  winner_id bigint REFERENCES game.users(id) ON DELETE SET NULL,
  battle_at text,
  host_delta integer,
  guest_delta integer,
  referee text
);

CREATE TABLE IF NOT EXISTS game.ratings (
  user_id bigint PRIMARY KEY REFERENCES game.users(id) ON DELETE CASCADE,
  rating integer NOT NULL DEFAULT 1000,
  wins integer NOT NULL DEFAULT 0,
  losses integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS game.online_match_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_id bigint NOT NULL REFERENCES game.online_matches(id) ON DELETE CASCADE,
  user_id bigint REFERENCES game.users(id) ON DELETE SET NULL,
  at text NOT NULL DEFAULT game.utc_text(),
  kind text NOT NULL,                      -- packet, seed, battle, result, leave, end, referee
  detail text
);
CREATE INDEX IF NOT EXISTS online_match_events_match ON game.online_match_events (match_id, id);

CREATE TABLE IF NOT EXISTS game.online_incidents (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES game.users(id) ON DELETE CASCADE,
  match_id bigint REFERENCES game.online_matches(id) ON DELETE SET NULL,
  at text NOT NULL DEFAULT game.utc_text(),
  kind text NOT NULL
);
CREATE INDEX IF NOT EXISTS online_incidents_user ON game.online_incidents (user_id, at);

CREATE TABLE IF NOT EXISTS game.online_match_saves (
  match_id bigint NOT NULL REFERENCES game.online_matches(id) ON DELETE CASCADE,
  side text NOT NULL,
  user_id bigint REFERENCES game.users(id) ON DELETE SET NULL,
  data bytea NOT NULL,
  slots text NOT NULL,
  PRIMARY KEY (match_id, side)
);

-- The referee's replays (referee.js).
CREATE TABLE IF NOT EXISTS game.referee_jobs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_id bigint NOT NULL REFERENCES game.online_matches(id) ON DELETE CASCADE,
  reason text NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  created_at text NOT NULL DEFAULT game.utc_text(),
  finished_at text,
  results text
);

-- Ranked bans (sanctions.js).
CREATE TABLE IF NOT EXISTS game.ranked_bans (
  user_id bigint PRIMARY KEY REFERENCES game.users(id) ON DELETE CASCADE,
  at text NOT NULL DEFAULT game.utc_text(),
  reason text NOT NULL,
  by_admin bigint REFERENCES game.users(id) ON DELETE SET NULL
);

-- Gifts from the admins (gifts.js).
CREATE TABLE IF NOT EXISTS game.gifts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES game.users(id) ON DELETE CASCADE,
  kind text NOT NULL,
  value integer NOT NULL,
  qty integer NOT NULL DEFAULT 1,
  note text,
  status text NOT NULL DEFAULT 'pending',
  by_admin bigint REFERENCES game.users(id) ON DELETE SET NULL,
  created_at text NOT NULL DEFAULT game.utc_text(),
  delivered_at text,
  bonus text,
  bonus_seen integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS gifts_pending ON game.gifts (user_id, status);

-- Last report of each play page (presence.js).
CREATE TABLE IF NOT EXISTS game.last_seen (
  user_id bigint PRIMARY KEY REFERENCES game.users(id) ON DELETE CASCADE,
  at text NOT NULL,
  state text NOT NULL
);

-- Friends and chat (social.js).
CREATE TABLE IF NOT EXISTS game.friend_requests (
  from_id bigint NOT NULL REFERENCES game.users(id) ON DELETE CASCADE,
  to_id bigint NOT NULL REFERENCES game.users(id) ON DELETE CASCADE,
  at text NOT NULL DEFAULT game.utc_text(),
  PRIMARY KEY (from_id, to_id)
);
CREATE TABLE IF NOT EXISTS game.friends (     -- both directions: (a, b) and (b, a)
  user_id bigint NOT NULL REFERENCES game.users(id) ON DELETE CASCADE,
  friend_id bigint NOT NULL REFERENCES game.users(id) ON DELETE CASCADE,
  since text NOT NULL DEFAULT game.utc_text(),
  PRIMARY KEY (user_id, friend_id)
);
CREATE TABLE IF NOT EXISTS game.chat_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  channel text NOT NULL,                   -- 'general', or 'dm:<lower id>:<higher id>'
  user_id bigint NOT NULL REFERENCES game.users(id) ON DELETE CASCADE,
  body text NOT NULL,
  at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS chat_channel ON game.chat_messages (channel, id);

-- PvP coins (shop.js): each player's balance, and every change to it. A won online battle pays
-- 5 coins (one row per match and winner, reason 'win'; 'revoked' once the referee or an admin
-- takes the win back); the shop's purchases are 'shop' rows with a negative delta and their gift.
CREATE TABLE IF NOT EXISTS game.wallets (
  user_id bigint PRIMARY KEY REFERENCES game.users(id) ON DELETE CASCADE,
  coins integer NOT NULL DEFAULT 0 CHECK (coins >= 0)
);
CREATE TABLE IF NOT EXISTS game.coin_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES game.users(id) ON DELETE CASCADE,
  delta integer NOT NULL,
  reason text NOT NULL,                    -- 'win', 'revoked', 'shop'
  match_id bigint REFERENCES game.online_matches(id) ON DELETE SET NULL,
  opponent_id bigint REFERENCES game.users(id) ON DELETE SET NULL,
  gift_id bigint REFERENCES game.gifts(id) ON DELETE SET NULL,
  item text,                               -- the shop's item id
  created_at text NOT NULL DEFAULT game.utc_text()
);
CREATE UNIQUE INDEX IF NOT EXISTS coin_log_match ON game.coin_log (match_id, user_id) WHERE match_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS coin_log_user ON game.coin_log (user_id, created_at);

-- The shop's catalogue, edited on /admin/shop (shop.js). kind 'digimon': value = species, bonus =
-- JSON array of bonus stats (gifts.js MAX_BONUS order); kind 'item': value = item index, qty per
-- purchase. discount: percent off until sale_ends (null = no end). stock: purchases left (null =
-- unlimited).
CREATE TABLE IF NOT EXISTS game.shop_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL CHECK (kind IN ('digimon', 'item')),
  value integer NOT NULL,
  qty integer NOT NULL DEFAULT 1,
  bonus text,
  price integer NOT NULL CHECK (price >= 0),
  discount integer NOT NULL DEFAULT 0 CHECK (discount BETWEEN 0 AND 100),
  sale_ends text,
  stock integer CHECK (stock >= 0),
  sold integer NOT NULL DEFAULT 0,
  active boolean NOT NULL DEFAULT true,
  sort integer NOT NULL DEFAULT 0,
  created_at text NOT NULL DEFAULT game.utc_text()
);

-- Events run from /admin/events (events.js): 'battle' (most online wins), 'contest' (best Digimon
-- handed over, rules = { level, species, stat }), 'collect' (most Digimon handed over). rewards: JSON
-- array of coins by place. status 'open', then 'paid' (results: the final standings) or 'cancelled'.
CREATE TABLE IF NOT EXISTS game.events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL CHECK (kind IN ('battle', 'contest', 'collect')),
  title text NOT NULL,
  body text,
  starts_at text NOT NULL,
  ends_at text NOT NULL,
  rules text,
  rewards text NOT NULL DEFAULT '[]',
  status text NOT NULL DEFAULT 'open',
  results text,
  created_by bigint REFERENCES game.users(id) ON DELETE SET NULL,
  created_at text NOT NULL DEFAULT game.utc_text()
);

-- The Digimon bank (bank.js): Digimon taken out of a player's farm, with the game's whole struct.
-- status: 'pending' (out of the farm, waiting for a save without it: name_count is how many
-- Digimon of that name the last save had), 'stored', 'event' (handed over to event_id),
-- 'withdrawing' (a gift brings it back: gift_id), 'out' (back on the farm, waiting for a save
-- with it), 'withdrawn', 'returned' (a save still had it: the deposit was undone). listed: offered
-- on the public trade board.
CREATE TABLE IF NOT EXISTS game.bank (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES game.users(id) ON DELETE CASCADE,
  species integer NOT NULL,
  name text NOT NULL,
  stats text NOT NULL,
  struct bytea NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  name_count integer NOT NULL DEFAULT 0,
  listed boolean NOT NULL DEFAULT false,
  event_id bigint REFERENCES game.events(id) ON DELETE SET NULL,
  gift_id bigint REFERENCES game.gifts(id) ON DELETE SET NULL,
  first_owner bigint REFERENCES game.users(id) ON DELETE SET NULL,
  created_at text NOT NULL DEFAULT game.utc_text(),
  updated_at text NOT NULL DEFAULT game.utc_text()
);
CREATE INDEX IF NOT EXISTS bank_user ON game.bank (user_id, status);
CREATE INDEX IF NOT EXISTS bank_event ON game.bank (event_id) WHERE event_id IS NOT NULL;

-- Trades between banks: 'direct' (from_user offers give_id for to_user's take_id) or 'bid' (an
-- offer on take_id, listed on the board by to_user). Accepting swaps the two owners.
CREATE TABLE IF NOT EXISTS game.trades (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL CHECK (kind IN ('direct', 'bid')),
  from_user bigint NOT NULL REFERENCES game.users(id) ON DELETE CASCADE,
  to_user bigint NOT NULL REFERENCES game.users(id) ON DELETE CASCADE,
  give_id bigint NOT NULL REFERENCES game.bank(id) ON DELETE CASCADE,
  take_id bigint NOT NULL REFERENCES game.bank(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'open',
  created_at text NOT NULL DEFAULT game.utc_text(),
  decided_at text
);
CREATE INDEX IF NOT EXISTS trades_to ON game.trades (to_user, status);
CREATE INDEX IF NOT EXISTS trades_from ON game.trades (from_user, status);

-- A gift that brings a banked Digimon back (bank.js); coins paid by an event or spent on an offer.
ALTER TABLE game.gifts ADD COLUMN IF NOT EXISTS bank_id bigint REFERENCES game.bank(id) ON DELETE SET NULL;
ALTER TABLE game.coin_log ADD COLUMN IF NOT EXISTS event_id bigint REFERENCES game.events(id) ON DELETE SET NULL;
ALTER TABLE game.coin_log ADD COLUMN IF NOT EXISTS shop_item_id bigint REFERENCES game.shop_items(id) ON DELETE SET NULL;

-- The site server's role (its login is created apart, with its password, see docs/supabase_database.md).
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'game_server') THEN
    CREATE ROLE game_server NOLOGIN;
  END IF;
END $$;
GRANT USAGE ON SCHEMA game TO game_server;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA game TO game_server;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA game TO game_server;
GRANT EXECUTE ON FUNCTION game.utc_text(interval) TO game_server;
ALTER DEFAULT PRIVILEGES IN SCHEMA game GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO game_server;
ALTER DEFAULT PRIVILEGES IN SCHEMA game GRANT USAGE, SELECT ON SEQUENCES TO game_server;
ALTER ROLE game_server SET search_path = game;
